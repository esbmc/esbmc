# #10311: round(x, n) rounds the exact binary value of x.
a = round(1.95, 1)
assert a == 1.9
b = round(-1.95, 1)
assert b == -1.9
c = round(-0.445, 2)
assert c == -0.45
d = round(2.675, 2)
assert d == 2.67
e = round(0.125, 2)
assert e == 0.12
f = round(25.0, -1)
assert f == 20.0
g = round(25.000001, -1)
assert g == 30.0
h = round(-35.0, -1)
assert h == -40.0
i = round(95.0, -1)
assert i == 100.0
j = round(7.0, -1)
assert j == 10.0
k = round(1.5, 400)
assert k == 1.5
m = round(1e300, -400)
assert m == 0.0
p = round(2.5, 4294967296)
assert p == 2.5
q = round(2.5, -4294967296)
assert q == 0.0
