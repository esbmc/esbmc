import random

n = random.randint(-9223372036854775807 - 1, 9223372036854775807)
s = str(n)
if n == -9223372036854775807 - 1:
    assert s == "-9223372036854775808"
if n == 9223372036854775807:
    assert s == "9223372036854775807"
if n == 0:
    assert s == "0"
if n == -1:
    assert s == "-1"
if n == -1000000007:
    assert s == "-1000000007"
