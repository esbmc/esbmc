import numpy as np

a = np.array([[4.0, 1.0, 0.0, 0.0], [1.0, 4.0, 1.0, 0.0], [0.0, 1.0, 4.0, 1.0],
              [0.0, 0.0, 1.0, 4.0]])
b = np.linalg.inv(a)
p00 = a[0][0] * b[0][0] + a[0][1] * b[1][0] + a[0][2] * b[2][0] + a[0][3] * b[3][0]
p10 = a[1][0] * b[0][0] + a[1][1] * b[1][0] + a[1][2] * b[2][0] + a[1][3] * b[3][0]
assert abs(p00 - 1.0) < 1e-9 and abs(p10) < 1e-9
