import numpy as np

a = np.array([[2.0, 1.0, 0.0], [1.0, 3.0, 1.0], [0.0, 1.0, 4.0]])
w, v = np.linalg.eig(a)
assert abs(a[0][0] * v[0][0] + a[0][1] * v[1][0] + a[0][2] * v[2][0] - w[0] * v[0][0]) < 1e-9
assert abs(a[1][0] * v[0][0] + a[1][1] * v[1][0] + a[1][2] * v[2][0] - w[0] * v[1][0]) < 1e-9
assert abs(a[2][0] * v[0][0] + a[2][1] * v[1][0] + a[2][2] * v[2][0] - w[0] * v[2][0]) < 1e-9
assert abs(v[0][0] * v[0][0] + v[1][0] * v[1][0] + v[2][0] * v[2][0] - 1.0) < 1e-9
assert abs(a[0][0] * v[0][1] + a[0][1] * v[1][1] + a[0][2] * v[2][1] - w[1] * v[0][1]) < 1e-9
assert abs(a[1][0] * v[0][1] + a[1][1] * v[1][1] + a[1][2] * v[2][1] - w[1] * v[1][1]) < 1e-9
assert abs(a[2][0] * v[0][1] + a[2][1] * v[1][1] + a[2][2] * v[2][1] - w[1] * v[2][1]) < 1e-9
assert abs(v[0][1] * v[0][1] + v[1][1] * v[1][1] + v[2][1] * v[2][1] - 1.0) < 1e-9
assert abs(a[0][0] * v[0][2] + a[0][1] * v[1][2] + a[0][2] * v[2][2] - w[2] * v[0][2]) < 1e-9
assert abs(a[1][0] * v[0][2] + a[1][1] * v[1][2] + a[1][2] * v[2][2] - w[2] * v[1][2]) < 1e-9
assert abs(a[2][0] * v[0][2] + a[2][1] * v[1][2] + a[2][2] * v[2][2] - w[2] * v[2][2]) < 1e-9
assert abs(v[0][2] * v[0][2] + v[1][2] * v[1][2] + v[2][2] * v[2][2] - 1.0) < 1e-9
assert abs(w[0] + w[1] + w[2] - 9.0) < 1e-9
