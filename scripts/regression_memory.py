#!/usr/bin/env python3
"""Build regression/MEMORY_COST from a ctest LastTest.log.

testing_tool.py prints each test's peak RSS as "mem_usage=<kB> kilobytes".
Every test whose peak reaches --threshold-mb is written as "<name> <GB>",
the GB rounded up; regression/CMakeLists.txt turns that into a ctest
RESOURCE_GROUPS "mem" cost.
"""

import argparse
import math
import re
import sys

TEST_RE = re.compile(r"^\d+/\d+ Test: (.+)$")
MEM_RE = re.compile(r"^mem_usage=(\d+) kilobytes$")


def parse(log_lines):
    """Map test name -> peak RSS in kB (None when the test printed none)."""
    peaks = {}
    name = None
    for line in log_lines:
        line = line.rstrip("\n")
        match = TEST_RE.match(line)
        if match:
            name = match.group(1)
            peaks.setdefault(name, None)
            continue
        match = MEM_RE.match(line)
        if match and name:
            kb = int(match.group(1))
            peaks[name] = max(kb, peaks[name] or 0)
    return peaks


def main():
    """Print MEMORY_COST for the given logs; list unmeasured tests on stderr."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("log", nargs="+", help="LastTest.log file(s); max per test wins")
    parser.add_argument("--threshold-mb", type=int, default=1024)
    args = parser.parse_args()

    peaks = {}
    for path in args.log:
        with open(path, encoding="utf-8", errors="replace") as log:
            for name, kb in parse(log).items():
                old = peaks.get(name)
                peaks[name] = kb if old is None else max(old, kb or 0)

    missing = sorted(n for n, kb in peaks.items() if kb is None and n.startswith("regression/"))
    for name in missing:
        print(f"no mem_usage: {name}", file=sys.stderr)

    threshold_kb = args.threshold_mb * 1024
    heavy = sorted((n for n, kb in peaks.items() if kb and kb >= threshold_kb),
                   key=lambda n: (-peaks[n], n))
    print("# Generated by scripts/regression_memory.py: peak RSS rounded up to GB.")
    for name in heavy:
        print(f"{name} {math.ceil(peaks[name] / (1024 * 1024))}")


if __name__ == "__main__":
    main()
